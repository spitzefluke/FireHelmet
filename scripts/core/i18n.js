function getCurrentLang() {
  return localStorage.getItem("siteLang") || "de";
}

function t(key, fallback) {
  const lang = getCurrentLang();
  const dict = translations[lang] || translations.de;
  return dict[key] || (translations.de[key] || fallback || key);
}

/* Wie t(), ersetzt aber zusätzlich {platzhalter} im Text.
   Beispiel: tFormat("wheel.status.spunToday", { streak: 3 }) */
function tFormat(key, params) {
  let text = t(key);
  if (params) {
    Object.keys(params).forEach((k) => {
      text = text.replace(`{${k}}`, params[k]);
    });
  }
  return text;
}

function applyTranslations() {
  const lang = getCurrentLang();
  const dict = translations[lang] || translations.de;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) {
      el.setAttribute("placeholder", dict[key]);
    }
  });

  // Tooltip (title) und Vorlesetext (aria-label) blieben bisher immer
  // auf Deutsch stehen, weil nur Text und Platzhalter uebersetzt wurden.
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (dict[key]) {
      el.setAttribute("title", dict[key]);
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria-label");
    if (dict[key]) {
      el.setAttribute("aria-label", dict[key]);
    }
  });

  document.documentElement.setAttribute("lang", lang);
  document.body.classList.toggle("lang-de", lang === "de");
  document.body.classList.toggle("lang-en", lang === "en");

  document.querySelectorAll(".lang-switch").forEach((switchEl) => {
    switchEl.classList.toggle("is-en", lang === "en");
    switchEl.setAttribute("aria-pressed", lang === "en" ? "true" : "false");
  });
}

function setLanguage(lang) {
  localStorage.setItem("siteLang", lang);
  applyTranslations();

  // Seiten, die ihre Inhalte per JS neu aufbauen, müssen nach dem
  // Sprachwechsel einmal neu gerendert werden (Status-Texte etc.)
  if (typeof refreshWheelStatus === "function") refreshWheelStatus();
  if (typeof loadLeaderboard === "function" && document.getElementById("leaderboard")?.classList.contains("active-page")) {
    loadLeaderboard();
  }
  // Auch das Story-Archiv und die Kapitelliste setzen ihre Texte
  // beim Rendern zusammen ("3 von 12 geoeffnet", "Gelesen"/"Gesperrt")
  // und tragen daher keine data-i18n-Marken.
  if (typeof loadStories === "function" && document.getElementById("story")?.classList.contains("active-page")) {
    loadStories();
  }
  if (typeof loadChapters === "function" && typeof currentStory !== "undefined" && currentStory
      && document.getElementById("story-detail")?.classList.contains("active-page")) {
    loadChapters();
  }
  // Die Startseiten-Uebersicht baut ihre Texte beim Rendern zusammen
  // und traegt daher keine data-i18n-Marken, die applyTranslations()
  // nachziehen koennte - sie muss neu aufgebaut werden.
  if (typeof fhRenderHomeDashboard === "function") fhRenderHomeDashboard();
  // Der Skill-Baum setzt Namen und Wirkungen beim Zeichnen per t() ein.
  if (typeof fhSkillNeuZeichnen === "function") fhSkillNeuZeichnen();
  if (typeof renderRarityLegend === "function") renderRarityLegend();
  if (typeof renderShopGrid === "function" && document.getElementById("shop")?.classList.contains("active-page")) {
    renderShopGrid({ quiet: true });
  }
}

// Vom neuen Toggle-Switch im Menü aufgerufen - wechselt einfach
// zwischen den beiden Sprachen hin und her
function toggleLanguage() {
  setLanguage(getCurrentLang() === "de" ? "en" : "de");
}

window.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
});
